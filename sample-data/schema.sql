-- Independent synthetic schema. Only the lab_owner superuser administers setup.
CREATE SCHEMA lab;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
REVOKE ALL ON DATABASE labdb FROM PUBLIC;
CREATE ROLE lab_tenant_north NOLOGIN;
CREATE ROLE lab_tenant_south NOLOGIN;
CREATE ROLE lab_anonymous NOLOGIN;
GRANT CONNECT ON DATABASE labdb TO lab_tenant_north, lab_tenant_south, lab_anonymous;
GRANT USAGE ON SCHEMA lab TO lab_tenant_north, lab_tenant_south;

CREATE TABLE lab.organizations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);
CREATE TABLE lab.assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES lab.organizations(id),
  asset_code text NOT NULL,
  status text NOT NULL CHECK (status IN ('ready', 'degraded', 'offline')),
  UNIQUE (organization_id, asset_code)
);
CREATE TABLE lab.recovery_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id bigint NOT NULL REFERENCES lab.assets(id),
  event_type text NOT NULL CHECK (event_type IN ('backup', 'restore', 'verify')),
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX recovery_events_asset_idx ON lab.recovery_events(asset_id);

-- Read-only tenant roles; no public grants, no role credentials, no BYPASSRLS.
GRANT SELECT ON lab.organizations, lab.assets, lab.recovery_events TO lab_tenant_north, lab_tenant_south;
ALTER TABLE lab.organizations ENABLE ROW LEVEL SECURITY;
ALTER TABLE lab.assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE lab.recovery_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE lab.organizations FORCE ROW LEVEL SECURITY;
ALTER TABLE lab.assets FORCE ROW LEVEL SECURITY;
ALTER TABLE lab.recovery_events FORCE ROW LEVEL SECURITY;

-- current_user is the active database role, not a user-settable session variable.
-- Static role-to-tenant mapping is deliberately limited to this synthetic lab.
CREATE POLICY org_tenant_read ON lab.organizations FOR SELECT TO lab_tenant_north, lab_tenant_south
  USING (id = CASE current_user WHEN 'lab_tenant_north' THEN 1 WHEN 'lab_tenant_south' THEN 2 ELSE NULL END);
CREATE POLICY asset_tenant_read ON lab.assets FOR SELECT TO lab_tenant_north, lab_tenant_south
  USING (organization_id = CASE current_user WHEN 'lab_tenant_north' THEN 1 WHEN 'lab_tenant_south' THEN 2 ELSE NULL END);
CREATE POLICY event_tenant_read ON lab.recovery_events FOR SELECT TO lab_tenant_north, lab_tenant_south
  USING (EXISTS (SELECT 1 FROM lab.assets a WHERE a.id = asset_id));
-- The referenced assets table is also protected by RLS for these roles.
